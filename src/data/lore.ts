/**
 * 배경 서술.
 *
 * 기획 방침은 프롬소프트웨어식이다. 컷신이나 대사로 설명하지 않고,
 * 방 안에 오브젝트를 놓아두기만 한다. **플레이어가 다가가지 않으면 아무것도
 * 읽지 못하고, 그래도 게임은 끝까지 진행된다.**
 *
 * 그래서 이 텍스트들은 전투 흐름을 끊지 않아야 한다. 한 문장에서 두 문장,
 * 다가가면 뜨고 멀어지면 사라진다. 읽었는지 여부를 게임이 기록하지도 않는다.
 *
 * 내용 규칙 하나: **엔딩의 반전을 문장으로 말하지 않는다.**
 * 적이 주인공의 과거와 얽혀 있다는 것, 여기가 정상적인 장소가 아니라는 것까지만
 * 흘리고, 그 이상은 플레이어가 이어 붙이게 둔다.
 */

export interface LoreNote {
  /** 방 안에서의 위치. 방 크기에 대한 비율이라 방이 커져도 자리가 유지된다. */
  at: { x: number; y: number };
  text: string;
}

